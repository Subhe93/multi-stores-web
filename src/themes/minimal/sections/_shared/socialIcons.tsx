/** Wrap a platform's path in a 24×24 <svg>. `currentColor` so callers can
 *  pick the colour via the parent's CSS `color`. Extra SVG props (width,
 *  height, style) pass through — useful for inline sizing in callers. */
export function SocialIconSvg({
  platform,
  title,
  ...svgProps
}: {
  platform: SocialPlatform;
  title?: string;
} & SVGProps<SVGSVGElement>): ReactElement {
  const def = PLATFORMS[platform];
  return (
    <svg
      viewBox="0 0 24 24"
      fill="currentColor"
      xmlns="http://www.w3.org/2000/svg"
      role={title ? 'img' : 'presentation'}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      {...svgProps}
    >
      {title && <title>{title}</title>}
      <path d={def.path} />
    </svg>
  );
}

/** Resolve the final href for a platform — auto-prefixes mailto: / tel:. */
export function resolveSocialHref(platform: SocialPlatform, rawUrl: string): string {
  const def = PLATFORMS[platform];
  if (def.prefixUrl) return def.prefixUrl(rawUrl);
  return rawUrl?.trim() || '#';
}

/** Brand colour lookup with a safe fallback. */
export function brandColor(platform: SocialPlatform): string {
  return PLATFORMS[platform]?.color || '#71717a';
}
